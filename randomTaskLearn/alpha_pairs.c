#include <unistd.h>

int	main(void)
{
	char	c;
	int		i;

	c = 'a';
	i = 0;
	while (i < 26)
	{
		if (i % 2 == 0)
		{
			write(1, &c, 1);
			write(1, &c, 1);
		}
		else
		{
			c = c - 32;
			write(1, &c, 1);
			write(1, &c, 1);
			c = c + 32;
		}
		c++;
		i++;
	}
	write(1, "\n", 1);
	return (0);
}